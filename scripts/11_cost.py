"""Compute cost per method (FUTURE_WORK item 14): time and memory of one training step of an output head, the cost of
the loss alone, parameter counts, and how the exact set likelihood scales with the number of levels K.

A head on frozen 768-d features, batch 256, Adam, as in the frozen-feature benchmark; times are medians of 200 steps
after a warm-up, on one configuration and on the 25-configuration ensemble the benchmark trains at once. Fine-tuning
is dominated by the backbone, so the loss changes its step time by well under 1%.

    python scripts/11_cost.py
Writes results/cost.csv, results/cost_exact_vs_K.csv and results/cost.md.
"""
import statistics
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from ordbench.paths import TABLES  # noqa: E402

import pandas as pd  # noqa: E402
import torch  # noqa: E402

from ordbench.heads import EnsembleHead, MemberAdam  # noqa: E402
from ordbench.losses import ALL_METHODS, HEAD_OF, OUTPUT_OF, compute_loss, output_dim  # noqa: E402
from ordbench.train import target_from_mask  # noqa: E402


def make_target(N, K, m, device):
    g = torch.Generator().manual_seed(0)
    ratings = torch.randint(0, K, (N, m), generator=g)
    counts = torch.zeros(N, K).scatter_add_(1, ratings, torch.ones(N, m))
    return target_from_mask(counts > 0, counts, m).to(device)


def sync():
    if torch.cuda.is_available():
        torch.cuda.synchronize()


def time_it(fn, steps=200, warmup=20):
    for _ in range(warmup):
        fn()
    sync()
    ts = []
    for _ in range(steps):
        t0 = time.perf_counter()
        fn()
        sync()
        ts.append(time.perf_counter() - t0)
    return statistics.median(ts) * 1e3


def measure(method, K, M, d=768, N=256, m=3, device="cuda"):
    T = make_target(N, K, m, device)
    x = torch.randn(N, d, device=device)
    head = EnsembleHead(M, d, output_dim(method, K), output=OUTPUT_OF[HEAD_OF[method]]).to(device)
    opt = MemberAdam(list(head.named_parameters()), [1e-3] * M, [1e-2] * M, head.decay_mask())

    def step():
        opt.zero_grad()
        compute_loss(method, head(x), T).sum().backward()
        opt.step()

    out = head(x).detach().requires_grad_(True)

    def loss_only():
        compute_loss(method, out, T).sum().backward()

    if device == "cuda":
        torch.cuda.reset_peak_memory_stats()
    step_ms = time_it(step)
    peak = torch.cuda.max_memory_allocated() / 2 ** 20 if device == "cuda" else float("nan")
    return dict(step_ms=step_ms, loss_ms=time_it(loss_only), peak_mb=peak,
                params_per_member=sum(p[0].numel() for p in head.parameters()) // M)


def main():
    device = "cuda" if torch.cuda.is_available() else "cpu"
    torch.backends.cuda.matmul.allow_tf32 = True
    for K in (5, 7):  # the first timed head runs several times faster than the same head later (cold start): discard it
        measure("ce_hard", K, 1, device=device)
        measure("ce_hard", K, 25, device=device)
    rows = []
    for method in ALL_METHODS:
        for K in (5, 7):
            one = measure(method, K, 1, device=device)
            ens = measure(method, K, 25, device=device)
            rows.append(dict(method=method, K=K, params=one["params_per_member"], step_ms_1=one["step_ms"],
                             loss_ms_1=one["loss_ms"], step_ms_25=ens["step_ms"], loss_ms_25=ens["loss_ms"],
                             peak_mb_25=ens["peak_mb"]))
        print(method, flush=True)
    df = pd.DataFrame(rows)
    df.to_csv(TABLES / "cost.csv", index=False)
    scale = []
    for K in range(3, 11):
        r = measure("exact_corn", K, 25, device=device)
        base = measure("soft_corn", K, 25, device=device)
        scale.append(dict(K=K, subsets=2 ** K - 1, exact_step_ms=r["step_ms"], soft_corn_step_ms=base["step_ms"],
                          ratio=r["step_ms"] / base["step_ms"], exact_peak_mb=r["peak_mb"]))
    sc = pd.DataFrame(scale)
    sc.to_csv(TABLES / "cost_exact_vs_K.csv", index=False)
    five = df[df.K == 5].set_index("method")
    lines = ["# Compute cost (auto-generated by scripts/11_cost.py)\n",
             f"Device: {torch.cuda.get_device_name(0) if device == 'cuda' else 'CPU'}. Head on 768-d features, batch 256, K = 5; "
             "median of 200 steps.\n",
             five[["params", "step_ms_1", "loss_ms_1", "step_ms_25", "loss_ms_25", "peak_mb_25"]].to_markdown(floatfmt=".3f"),
             "", "## Exact set likelihood against the number of levels (25-member ensemble, m = 3)\n",
             sc.to_markdown(index=False, floatfmt=".3f"), ""]
    (TABLES / "cost.md").write_text("\n".join(lines), encoding="utf8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
